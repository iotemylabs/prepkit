func writeStatic(t *testing.T) (dir string, files map[string]string) {
	t.Helper()
	s := populated(t)
	inv, err := s.Snapshot(ctx)
	if err != nil {
		t.Fatal(err)
	}
	dir = filepath.Join(t.TempDir(), "static")
	now := time.Date(2026, 7, 24, 12, 0, 0, 0, time.UTC)
	if err := Static(dir, *inv, now); err != nil {
		t.Fatal(err)
	}
	files = map[string]string{}
	entries, err := os.ReadDir(dir)
	if err != nil {
		t.Fatal(err)
	}
	for _, e := range entries {
		b, err := os.ReadFile(filepath.Join(dir, e.Name()))
		if err != nil {
			t.Fatal(err)
		}
		files[e.Name()] = string(b)
	}
	return dir, files
}

func TestStaticStructureAndContent(t *testing.T) {
	_, files := writeStatic(t)

	index, ok := files["index.html"]
	if !ok {
		t.Fatal("index.html missing")
	}
	if _, ok := files["kits.html"]; !ok {
		t.Fatal("kits.html missing")
	}

	// One kit page, linked from the index.
	var kitFile string
	for name := range files {
		if strings.HasPrefix(name, "kit-") {
			kitFile = name
		}
	}
	if kitFile == "" {
		t.Fatal("no kit manifest page generated")
	}
	if !strings.Contains(index, kitFile) {
		t.Error("index does not link the kit page directly")
	}

	kit := files[kitFile]
	for _, want := range []string{
		"Home 72h",
		"Emergency radio",
		"Midland ER310", // product names are ordinary data
		"2026-11-01",    // lot expiry dates are the point of the manifest
		"best by",       // expiry basis distinguished per the schema
		"Last physically verified: 2026-06-01",
		"Comms", // category grouping
	} {
		if !strings.Contains(kit, want) {
			t.Errorf("kit manifest missing %q", want)
		}
	}

	// The export_ok plan gets a page; the identity document and the
	// non-consenting contact sheet do not exist anywhere.
	planFound := false
	for name, content := range files {
		if strings.HasPrefix(name, "doc-") && strings.Contains(content, "meet at the library") {
			planFound = true
		}
	}
	if !planFound {
		t.Error("export_ok plan document not rendered")
	}
	if _, ok := files["contacts.html"]; ok {
		t.Error("contacts.html generated though the only contact sheet has export_ok=false")
	}
}

// TestStaticSelfContained greps every generated byte for anything that
// could execute or reach off-device. The export must render on a
// decade-old e-reader and must be structurally incapable of phoning
// anywhere.
func TestStaticSelfContained(t *testing.T) {
	_, files := writeStatic(t)
	forbidden := []string{
		"<script", "javascript:", "onclick", "onload",
		"http://", "https://", "//", "url(", "@import", "@font-face",
		"<link", "<img", "<iframe", "<object", "<embed", "<video", "<audio",
		"src=", "fetch(", "XMLHttpRequest",
	}
	for name, content := range files {
		lower := strings.ToLower(content)
		for _, f := range forbidden {
			if strings.Contains(lower, f) {
				t.Errorf("%s contains forbidden token %q", name, f)
			}
		}
	}
}

// TestStaticExcludesSensitive asserts by grep that nothing classified
// sensitive survives into the offline pages: the device this export lives
// on is exactly the one that gets lost or stolen.
func TestStaticExcludesSensitive(t *testing.T) {
	_, files := writeStatic(t)
	sensitive := map[string]string{
		"item serial":              "SN-99887",
		"item cost":                "59.99",
		"container location note":  "back wall",
		"person needs":             "daily medication",
		"identity document body":   "secret",
		"identity document title":  "Passport scans",
		"non-consenting doc body":  "the Larsens",
		"non-consenting doc title": "Neighborhood contacts",
	}
	for name, content := range files {
		for what, token := range sensitive {
			if strings.Contains(content, token) {
				t.Errorf("%s leaks %s (%q)", name, what, token)
			}
		}
	}
}

// TestStaticTwoTapRule: every generated page is reachable within two links
// of the index.
func TestStaticTwoTapRule(t *testing.T) {
	_, files := writeStatic(t)
	hrefs := regexp.MustCompile(`href="([^"]+)"`)
	linksFrom := func(content string) []string {
		var out []string
		for _, m := range hrefs.FindAllStringSubmatch(content, -1) {
			out = append(out, m[1])
		}
		return out
	}
	reachable := map[string]bool{"index.html": true}
	tap1 := linksFrom(files["index.html"])
	for _, l := range tap1 {
		reachable[l] = true
	}
	for _, l := range tap1 {
		for _, l2 := range linksFrom(files[l]) {
			reachable[l2] = true
		}
	}
	for name := range files {
		if !reachable[name] {
			t.Errorf("%s is more than two taps from the index", name)
		}
	}
}

func TestStaticRefusesNonEmptyDir(t *testing.T) {
	s := populated(t)
	inv, err := s.Snapshot(ctx)
	if err != nil {
		t.Fatal(err)
	}
	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, "stale.html"), []byte("old"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := Static(dir, *inv, time.Now()); err == nil || !strings.Contains(err.Error(), "not empty") {
		t.Errorf("got %v, want non-empty refusal", err)
	}
}
